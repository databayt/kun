#!/usr/bin/env node
// compile-words.mjs — one word in, every form of it out.
//
//   node .claude/scripts/compile-words.mjs            write the generated door skills and reference agents
//   node .claude/scripts/compile-words.mjs --check    write nothing; exit 1 and list every missing or drifted form
//   node .claude/scripts/compile-words.mjs --list     one line per word with its forms
//
// A word is the keyword, the skill (the slash command), the agent and the vocabulary spell.
//
//   department word  (video, image, marketing, sales, business, support, tech, rnd)
//     source   departments/<word>/pack.json
//     pack     exists                                   (hand-written)
//     agent    .claude/agents/<word>.md, name: <word>   (hand-written, never generated)
//     skill    .claude/skills/<word>/SKILL.md           (GENERATED: the department's door)
//     spell    a vocabulary spell named <word>, familiar <word>, skill /<word>
//     keyword  the resolver reads the pack (name, title_ar, keywords) — nothing to generate
//
//   repo word  (kun, hogwarts, mkan, codebase, catalog — repos a pack lists in `repos`)
//     source   .claude/memory/repositories.json         (the word is `word`, else the id)
//     agent    .claude/agents/<word>.md  — kept when hand-written (hogwarts, mkan), else GENERATED
//     skill    .claude/skills/<word>/SKILL.md — kept when hand-written (codebase), else GENERATED
//
// Every generated file carries a marker comment right after its frontmatter; the script only
// ever overwrites a file that carries it. lane: is stamped by compile-lanes.mjs, not here.
// It runs by hand and inside build-plugin.sh; --check is for hooks and lint.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadLanes, expected } from "./compile-lanes.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const MARK = "Generated by .claude/scripts/compile-words.mjs";
const tilde = (p) => (p && p.startsWith(os.homedir()) ? "~" + p.slice(os.homedir().length) : p);
const readJSON = (p, d = null) => {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return d;
  }
};
const read = (p) => (fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null);
const fmName = (raw) => /^---\n[\s\S]*?^name:\s*["']?([^"'\n]+?)["']?\s*$/m.exec(raw || "")?.[1] ?? null;
const fmKey = (raw, key) => new RegExp(`^${key}:\\s*(.*)$`, "m").exec((raw || "").split("\n---")[0])?.[1]?.trim() ?? null;

// ── sources ────────────────────────────────────────────────────────────────
export function departments(root = ROOT) {
  const dir = path.join(root, "departments");
  const out = [];
  for (const d of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
    const pack = readJSON(path.join(dir, d, "pack.json"));
    if (pack?.name) out.push({ word: pack.name, dir: d, pack });
  }
  return out;
}
export function repoWords(root = ROOT, depts = departments(root)) {
  const reg = readJSON(path.join(root, ".claude/memory/repositories.json"), {});
  const listed = new Set(depts.flatMap((d) => d.pack.repos || []));
  const out = [];
  for (const group of Object.values(reg.repositories || {})) {
    for (const r of group || []) if (r?.id && listed.has(r.id)) out.push({ word: r.word || r.id, id: r.id, repo: r });
  }
  return out;
}

// ── what each generated file must say ──────────────────────────────────────
// the knobs compile-lanes.mjs stamps for a door skill, so the two scripts never disagree
const doorEffort = () => expected("skill", "build", loadLanes(ROOT)).effort;
const short = (s, n = 60) => (s.length <= n ? s : s.slice(0, n - 1).trimEnd() + "…");
const q = (s) => JSON.stringify(s);

function deptSkill(d) {
  const { word, pack } = d;
  const repos = (pack.repos || []).join(" · ");
  const tools = (pack.items || []).map((i) => (i.startsWith("skill:") ? "`/" + i.slice(6) + "`" : "the `" + i.slice(6) + "` agent")).join(" · ");
  return `---
name: ${word}
description: ${q(short(`The ${word} department: board, formulas, the lead`))}
lane: build
effort: ${doorEffort()}
---

<!-- ${MARK} from departments/${d.dir}/pack.json — edit the pack and re-run it; this file is overwritten. -->

# ${word}

${pack.description || pack.title}

Request: $ARGUMENTS — if it names a repo (${repos}), add \`--repo <repo>\` to every station call below.

1. **No request** — run \`node ~/kun/.claude/scripts/station.mjs board --dept ${word} [--repo <repo>] --json\` and show its up-to-three options (\`label_en\` / \`label_ar\`, \`why\`). The person taps one or types text.
2. **A request** — run \`node ~/kun/.claude/scripts/station.mjs match "<text>" --dept ${word} [--repo <repo>] --json\`.
   - It names a formula (\`id\`): run \`node ~/kun/.claude/scripts/station.mjs fill <id> --dept ${word} [--repo <repo>] --json\`, show the filled \`prompt\`, ask for anything in \`missing\`, then hand it to the \`${word}\` agent on the \`route\` the fill returns.
   - \`id\` is null: no formula fits. Hand the request to the \`${word}\` agent in the department's frame (\`departments/${word}/pack.json\` → \`formula.en\`: Task · Context · References · Constraints · Deliverable).
3. The agent plans and judges; building goes to cheaper lanes with a written brief. It stops at every human gate and never approves.

Tools of the department: ${tools}.
`;
}

function repoSkill(r) {
  const p = tilde(r.repo.local || path.join(os.homedir(), r.id));
  return `---
name: ${r.word}
description: ${q(short(`The ${r.word} place: its rules, blocks, open issues`))}
lane: build
effort: ${doorEffort()}
---

<!-- ${MARK} from .claude/memory/repositories.json — edit the registry and re-run it; this file is overwritten. -->

# ${r.word}

${r.repo.description || r.repo.name} (\`databayt/${r.id}\`, at \`${p}\`).

Request: $ARGUMENTS

1. Read \`${p}/CLAUDE.md\` and \`${p}/.claude/CLAUDE.md\`, and \`${p}/.claude/blocks.json\` if it exists.
2. See what is open: \`gh issue list --repo databayt/${r.id} --state open --limit 20\`.
3. Carry the request out in that place, under that repo's own rules, with absolute paths. Work on \`main\`.
`;
}

function repoAgent(r) {
  const purpose = (r.repo.purpose || []).join(", ");
  const p = tilde(r.repo.local || path.join(os.homedir(), r.id));
  return `---
name: ${r.word}
description: ${q(short(`${r.repo.name} reference — ${purpose}`, 110))}
model: sonnet
effort: low
version: "databayt"
handoff: [tech]
lane: research
---

<!-- ${MARK} from .claude/memory/repositories.json — edit the registry and re-run it; this file is overwritten. -->

# ${r.repo.name} Reference Agent

**Repo**: databayt/${r.id} (\`${p}\`) | **Purpose**: ${purpose}

${r.repo.description || ""}

Read the repo's own \`CLAUDE.md\` before answering, cite files by path, and say when something is not there.
`;
}

// ── plan: every file the words need, and what state it is in ───────────────
export function plan(root = ROOT) {
  const depts = departments(root);
  const repos = repoWords(root, depts);
  const vocab = readJSON(path.join(root, ".claude/vocabulary.json"), {});
  const spells = new Map((vocab.schools || []).flatMap((s) => s.spells || []).map((sp) => [sp.name, sp]));
  const items = [];
  const problems = [];
  const file = (kind, word, rel, body, handWritten, keepHand = false) => {
    const p = path.join(root, rel);
    const have = read(p);
    const generated = have !== null && have.includes(MARK);
    const item = { kind, word, rel, path: p, body, have, generated, state: "ok", handWritten };
    if (have === null) item.state = handWritten ? "missing" : "write";
    else if (generated) item.state = have === body ? "ok" : "drift";
    else item.state = handWritten || keepHand ? "ok" : "blocked";
    items.push(item);
    return item;
  };
  for (const d of depts) {
    const sk = file("skill", d.word, `.claude/skills/${d.word}/SKILL.md`, deptSkill(d), false);
    if (sk.state === "blocked") problems.push(`skill ${d.word}: ${sk.rel} exists and is not generated — a department's door is generated, move the hand-written file away`);
    const ag = file("agent", d.word, `.claude/agents/${d.word}.md`, null, true);
    if (ag.state === "ok" && fmName(ag.have) !== d.word) problems.push(`agent ${d.word}: ${ag.rel} has name "${fmName(ag.have)}", expected "${d.word}"`);
    if (ag.state === "ok" && !fmKey(ag.have, "lane")) problems.push(`agent ${d.word}: no lane declared`);
    const sp = spells.get(d.word);
    const orders = (sp?.order || []).map((o) => `${o.type}:${o.name}`);
    if (!sp) problems.push(`spell ${d.word}: no vocabulary spell named "${d.word}" (.claude/vocabulary.json)`);
    else if (!orders.includes(`familiar:${d.word}`) || !orders.includes(`skill:/${d.word}`)) problems.push(`spell ${d.word}: order must name familiar ${d.word} and skill /${d.word}`);
    if (!d.pack.title_ar) problems.push(`pack ${d.word}: no title_ar (the Arabic keyword)`);
  }
  for (const r of repos) {
    file("agent", r.word, `.claude/agents/${r.word}.md`, repoAgent(r), false, true);
    file("skill", r.word, `.claude/skills/${r.word}/SKILL.md`, repoSkill(r), false, true);
  }
  return { depts, repos, items, problems };
}

function list(pl) {
  const st = (kind, word) => pl.items.find((i) => i.kind === kind && i.word === word);
  const mark = (i) => (!i ? "—" : i.state === "ok" ? (i.generated ? "generated" : "hand") : i.state);
  const vocab = readJSON(path.join(ROOT, ".claude/vocabulary.json"), {});
  const spells = new Set((vocab.schools || []).flatMap((s) => s.spells || []).map((sp) => sp.name));
  for (const d of pl.depts) console.log(`dept  ${d.word.padEnd(10)} pack ✓ · agent ${mark(st("agent", d.word))} · skill ${mark(st("skill", d.word))} · spell ${spells.has(d.word) ? "✓" : "missing"} · keywords ${[d.word, d.pack.title_ar, ...(d.pack.keywords?.en || []), ...(d.pack.keywords?.ar || [])].filter(Boolean).length}`);
  for (const r of pl.repos) console.log(`repo  ${r.word.padEnd(10)} registry ✓ (${r.id}) · agent ${mark(st("agent", r.word))} · skill ${mark(st("skill", r.word))}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2] || "";
  const pl = plan();
  if (mode === "--list") {
    list(pl);
  } else if (mode === "--check") {
    const bad = pl.items.filter((i) => i.state !== "ok").map((i) => `${i.state}: ${i.rel}`);
    const all = [...bad, ...pl.problems];
    for (const l of all) console.error(l);
    if (all.length) {
      console.error(`compile-words: ${all.length} problem(s) — run node .claude/scripts/compile-words.mjs`);
      process.exit(1);
    }
    console.log(`compile-words: ${pl.depts.length} department words + ${pl.repos.length} repo words, every form present`);
  } else {
    let wrote = 0;
    for (const i of pl.items) {
      if ((i.state === "write" || i.state === "drift") && i.body) {
        fs.mkdirSync(path.dirname(i.path), { recursive: true });
        fs.writeFileSync(i.path, i.body);
        wrote++;
        console.log(`wrote ${i.rel}`);
      }
    }
    const left = [...pl.items.filter((i) => i.state === "missing" || i.state === "blocked").map((i) => `${i.state}: ${i.rel}`), ...pl.problems];
    for (const l of left) console.error(l);
    console.log(`compile-words: wrote ${wrote} file(s), ${pl.items.length - wrote} unchanged`);
    if (left.length) process.exit(1);
  }
}

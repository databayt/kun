#!/bin/bash
# hermes-gate.sh — Hermes' Python cron jobs run only in a real wake (2026-11-02).
#
#   hermes-gate.sh <hermes:job> <needs,…> <script.py>   run it (what each generated wrapper calls)
#   hermes-gate.sh --install [--dry]                    write the wrappers, point the jobs at them
#
# Hermes' ticker fires in the Mac's dark wakes too (lid shut, 2–30 s, no real network): the Python
# jobs failed on DNS there, and hogwarts-crm-activity moved its watermark before its Slack send
# failed — that activity was lost for good. Through this gate a job runs only in a full wake with
# the network and what it needs (kun lib/runs.sh runs_ready). Otherwise it prints nothing (Hermes:
# a silent ok), records `defer`, and the supervisor re-runs the slot once the Mac is up. Either way
# the run lands on the job's record (~/.claude/state/runs/hermes_<name>.json), which runs.sh judges.
# Hermes still runs the script with its own Python, as it ran the .py directly before.

PY="${HERMES_PYTHON:-$HOME/.hermes/hermes-agent/venv/bin/python}"
DIR="${HERMES_SCRIPTS:-$HOME/.hermes/scripts}"

# name|needs|script — the gated jobs (the mkan lanes gate themselves in lane.sh).
GATED='hogwarts-crm-digest|network,twenty|hogwarts-crm-digest.py
hogwarts-crm-activity|network,twenty|hogwarts-crm-activity.py
hogwarts-snapshot-freshness|network,twenty|snapshot-freshness.py
databayt-weekly-social-plan|network|databayt-social-planner.py
databayt-daily-social-digest|network|databayt-social-digest.py'

if [ "${1:-}" = "--install" ]; then
    DRY=""
    [ "${2:-}" = "--dry" ] && DRY=1
    echo "$GATED" | while IFS='|' read -r name needs script; do
        w="$DIR/gated-$name.sh"
        id=$(python3 -c 'import json, sys
d = json.load(open(sys.argv[1])); jobs = d["jobs"] if isinstance(d, dict) else d
print(next((j["id"] for j in jobs if j.get("name") == sys.argv[2]), ""))' "$HOME/.hermes/cron/jobs.json" "$name")
        [ -n "$id" ] || { echo "! $name: no such Hermes job"; continue; }
        [ -f "$DIR/$script" ] || { echo "! $name: $script missing"; continue; }
        if [ -n "$DRY" ]; then echo "would gate $name ($id) → gated-$name.sh ($needs)"; continue; fi
        printf '%s\n' '#!/bin/bash' \
            "# Generated by kun .claude/scripts/hermes-gate.sh --install: $name runs only in a real wake." \
            "exec /bin/bash \"\$HOME/.claude/scripts/hermes-gate.sh\" hermes:$name $needs $script" >"$w.new"
        chmod 755 "$w.new" && mv "$w.new" "$w"
        hermes cron edit "$id" --script "gated-$name.sh" >/dev/null 2>&1 && echo "gated $name → gated-$name.sh" || echo "! $name: hermes cron edit failed"
    done
    exit 0
fi

JOB="${1:?usage: hermes-gate.sh <hermes:job> <needs,…> <script.py>}"
NEEDS="${2:-network}"
SCRIPT="${3:?script}"
# Without kun's library the job runs as it always did.
. "$HOME/.claude/scripts/lib/runs.sh" 2>/dev/null || exec "$PY" "$DIR/$SCRIPT"
# shellcheck disable=SC2086
if ! runs_ready "${GATE_WAIT:-2}" ${NEEDS//,/ }; then
    runs_record "$JOB" defer "$(runs_not_ready ${NEEDS//,/ })"
    exit 0
fi
_runs_mypid me
runs_record "$JOB" start "" 0 "" "$me"
out=$("$PY" "$DIR/$SCRIPT")
rc=$?
if [ "$rc" -eq 0 ]; then runs_record "$JOB" ok; else runs_record "$JOB" fail "$SCRIPT exit $rc"; fi
# Hermes delivers stdout; empty stays a silent run.
[ -n "$out" ] && printf '%s\n' "$out"
exit "$rc"

#!/usr/bin/env node
// references.mjs — write content/docs/references.mdx: what the engine watches, and how it
// reaches the outside world. Generated from two registries so it cannot drift from them:
//   .claude/engine.json → sync (the sources the `sync` skill reads, by tier and cadence)
//   .claude/mcp.json    → the MCP catalog (what setup.sh registers, and what it only documents)
//
//   node .claude/scripts/references.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const engine = JSON.parse(fs.readFileSync(path.join(ROOT, ".claude/engine.json"), "utf8"));
const mcp = JSON.parse(fs.readFileSync(path.join(ROOT, ".claude/mcp.json"), "utf8")).mcpServers || {};
const sync = engine.sync || {};
const TIERS = {
  anthropic: "Anthropic — Claude Code, the API, the models. The engine configures these rather than rebuilding them, so it follows them most closely.",
  stack: "The stack — the frameworks every product is built on.",
  services: "Services — where the products run and what they talk to.",
  practice: "Practice — how other teams run agents, and methods worth borrowing.",
};
// MDX reads a bare < or { as JSX, so anything that is not a link is escaped
const esc = (x) => String(x).replace(/</g, "&lt;").replace(/\{/g, "&#123;");
const link = (x) => {
  const gh = /^gh:([\w.-]+\/[\w.-]+)(.*)$/.exec(x);
  if (gh) return `[${gh[1]}](https://github.com/${gh[1]})${esc(gh[2])}`;
  const url = /^(https?:\/\/[^\s<]+)(.*)$/.exec(x);
  if (url) return `[${url[1].replace(/^https?:\/\//, "")}](${url[1]})${esc(url[2])}`;
  return esc(x);
};
const cell = (x) => String(x || "").replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\n/g, " ");

const L = ["---", "title: References", "description: What the engine watches, and how it reaches the outside world", "---", ""];
L.push("{/* Generated by node .claude/scripts/references.mjs — edit engine.json (sync.sources) or mcp.json, not this file. */}", "");
L.push("Kun configures other people's tools instead of rebuilding them, so it has to keep up with them. This page lists every source the engine reads on a schedule and every server it can call. The `sync` skill reads the sources tier by tier, adopts what is mechanical, and proposes the rest.", "");
L.push("## What the engine watches", "");
for (const [tier, why] of Object.entries(TIERS)) {
  const items = (sync.sources || {})[tier] || [];
  if (!items.length) continue;
  L.push(`### ${tier}`, "", `${why} Read every ${sync.cadence_days?.[tier] ?? "?"} days.`, "");
  for (const x of items) L.push(`- ${link(x)}`);
  L.push("");
}
L.push("The fifth tier, `self`, has no outside source: it is the engine's own run evidence (the ledger, the router's hit log, the health checks), read every " + (sync.cadence_days?.self ?? "?") + " days.", "");
L.push("## How it reaches them", "", "The MCP catalog in `.claude/mcp.json`. `setup.sh` registers a server unless the catalog marks it as documentation only.", "");
L.push("| Server | What it is for | Registered by setup |", "| --- | --- | --- |");
for (const [name, v] of Object.entries(mcp).sort((a, b) => a[0].localeCompare(b[0]))) {
  L.push(`| \`${name}\` | ${cell(v.description) || "—"} | ${v.$skipRegistration ? "no — catalog only" : "yes"} |`);
}
L.push("", "Which servers are actually called, and by whom, is measured rather than assumed: `node .claude/scripts/usage.mjs` counts the calls in the session transcripts.", "");
L.push("## See also", "", "- [Repositories](/docs/repositories) — the databayt repos the engine reads patterns from", "- [Places](/docs/places) — every repository and block keyword", "- [MCP](/docs/mcp) — how servers are configured", "");
fs.writeFileSync(path.join(ROOT, "content/docs/references.mdx"), L.join("\n"));
console.log(`references: wrote content/docs/references.mdx (${Object.values(sync.sources || {}).filter(Array.isArray).reduce((n, a) => n + a.length, 0)} sources, ${Object.keys(mcp).length} servers)`);

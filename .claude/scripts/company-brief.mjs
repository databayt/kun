#!/usr/bin/env node
// company-brief.mjs — compiles departments/_shared/company.md: what the company is chasing this week, in 40 lines or fewer.
//
//   node .claude/scripts/company-brief.mjs            write departments/_shared/company.md
//   node .claude/scripts/company-brief.mjs --stdout   print it, write nothing
//   node .claude/scripts/company-brief.mjs --check    exit 1 when the file on disk is out of date
//   node .claude/scripts/company-brief.mjs --test     golden checks, no files written
//
// Sources, all in this repo, none invented here:
//   .claude/CLAUDE.md             the Drive
//   docs/NORTH-STAR.md            the metric and the break-even line
//   .claude/memory/north_star.json  the current value, the targets, the pilot's latest read
//   docs/EPICS.md                 the epic in flight
//   content/docs/sprint.mdx       the sprint goal
//   content/media/markets.json    the price
// The Machine app appends the file to the workspace CLAUDE.md the same way as departments/_shared/ask.md, and the
// video plan formula reads its "Why this film" section through the station context key `company.why`.
// Node built-ins only. The pilot's name is a constant below: it is the one fact no document names as a field.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const SELF = fileURLToPath(import.meta.url)
const ROOT = path.resolve(path.dirname(SELF), "../..")
export const OUT = path.join(ROOT, "departments", "_shared", "company.md")
export const MAX_LINES = 40
const PILOT = "Al-Ibda"

const read = (rel) => {
  try {
    return fs.readFileSync(path.join(ROOT, rel), "utf8")
  } catch {
    return ""
  }
}
const readJson = (rel) => {
  try {
    return JSON.parse(read(rel))
  } catch {
    return {}
  }
}
const flat = (s) => String(s ?? "").replace(/\*\*|`/g, "").replace(/\[([^\]]+)\]\([^)]*\)/g, "$1").replace(/\s+/g, " ").trim()
const sentences = (s) => flat(s).split(/(?<=[.!?])\s+/).filter(Boolean)

// The Drive: the paragraph under "## The Drive" in .claude/CLAUDE.md, first two sentences.
export function drive(text) {
  const m = /^## The Drive\s*\n+([\s\S]*?)(?:\n## |$)/m.exec(text)
  const s = sentences(m?.[1] ?? "")
  return s.slice(0, 3).join(" ") || "Cash flow first. Break-even or bust."
}
// The metric: the bold line under "## The metric", plus the break-even count.
export function metric(text) {
  const m = /^## The metric\s*\n+\*\*([^*]+)\*\*/m.exec(text)
  const be = /that is \*\*([^*]+schools?)\*\*/i.exec(text)
  return { name: (m?.[1] ?? "Active paying schools using Hogwarts").replace(/\.$/, ""), breakEven: be ? flat(be[1]) : null }
}
// The sprint goal: "(Sprint 1, 8–21 November 2026: close our first school)" in the sprint page.
export function sprintGoal(text) {
  const m = /\((Sprint \d+[^:()]*:[^()]+)\)/.exec(text)
  return m ? flat(m[1]) : null
}
// The epic in flight: the "In Progress" row of the epic table.
export function epicInFlight(text) {
  const m = /^\|\s*(E\d+:[^|]+?)\s*\|[^|]*\|[^|]*\|\s*(P\d)\s*\|\s*In Progress\s*\|/m.exec(text)
  return m ? `${m[1].trim()} (${m[2]}, in progress)` : null
}
const priceLine = (markets) => {
  const rows = Object.entries(markets).filter(([, v]) => v && typeof v === "object" && v.name && v.price != null && v.currency)
  const by = new Map()
  for (const [, v] of rows) by.set(`${v.price} ${v.currency}`, [...(by.get(`${v.price} ${v.currency}`) ?? []), v.name.en])
  return [...by].map(([p, names], i) => `${p}${i === 0 ? " per student per year" : ""} in ${names.join(", ")}`).join("; ")
}

export function compile(src = {}) {
  const claude = src.claude ?? read(".claude/CLAUDE.md")
  const star = src.star ?? read("docs/NORTH-STAR.md")
  const ns = src.ns ?? readJson(".claude/memory/north_star.json")
  const epics = src.epics ?? read("docs/EPICS.md")
  const sprint = src.sprint ?? read("content/docs/sprint.mdx")
  const markets = src.markets ?? readJson("content/media/markets.json")

  const d = drive(claude)
  const m = metric(star)
  const goal = sprintGoal(sprint)
  const epic = epicInFlight(epics)
  const prices = priceLine(markets)
  const history = (ns.weekly_history ?? []).filter((h) => h.note && flat(h.note).includes(PILOT)).at(-1)
  const noteS = history ? sentences(history.note) : []
  const read1 = noteS.find((s) => s.includes(PILOT) && !/^Week target/.test(s))
  const target = noteS.find((s) => /^Week target/.test(s))
  const next = (ns.targets ?? []).find((t) => t.status === "open")
  const current = ns.current_value
  const when = ns.last_updated

  const lines = [
    "# Company brief",
    "",
    "<!-- Generated by .claude/scripts/company-brief.mjs from the Drive, NORTH-STAR.md, north_star.json, EPICS.md, sprint.mdx and markets.json. Do not edit by hand. -->",
    "",
    "## The Drive",
    d,
    "",
    "## North Star",
    `${m.name}. Now: ${current ?? "unknown"}${when ? ` (measured ${when})` : ""}.${next ? ` Next target: ${next.target} by ${next.date}.` : ""}${m.breakEven ? ` Break-even: ${m.breakEven}.` : ""}`,
    "",
    "## Sprint",
    goal ?? "No sprint goal found.",
    ...(epic ? [`Epic in flight: ${epic}.`] : []),
    "",
    "## Pilot",
    `${PILOT} is client #1.${read1 ? ` ${read1}` : ""}${target ? ` ${target}` : ""}`,
    "",
    "## Price",
    prices ? `${prices}.` : "No price found.",
    "",
    "## Why this film",
    `A film earns its place only if it moves a school toward paying. North Star: ${current ?? "?"} active paying schools${next ? ` (target ${next.target} by ${next.date})` : ""}. Sprint: ${goal ? goal.replace(/^Sprint \d+[^:]*:\s*/, "") : "n/a"}. Pilot: ${PILOT}, client #1. Price: ${prices || "n/a"}. Show the product working, name the price, end on one next step.`,
  ]
  return lines.map((l) => l.replace(/\s+$/, "")).join("\n") + "\n"
}

function runTests() {
  let pass = 0
  const fails = []
  const t = (name, fn) => {
    try {
      fn()
      pass++
      console.log(`  ok  ${name}`)
    } catch (e) {
      fails.push(name)
      console.log(`  FAIL ${name}: ${e.message}`)
    }
  }
  const ok = (c, m) => {
    if (!c) throw new Error(m)
  }
  t("drive: the first sentences of the Drive paragraph", () => ok(/^Cash flow first\. Break-even or bust\./.test(drive("## The Drive\n\n**Cash flow first. Break-even or bust.** This drive governs.\n\n## Next")), "drive"))
  t("metric and break-even are read from NORTH-STAR", () => {
    const r = metric("## The metric\n\n**Active paying schools using Hogwarts.**\n\nx that is **4–5 active paying schools**. y")
    ok(r.name === "Active paying schools using Hogwarts" && r.breakEven === "4–5 active paying schools", JSON.stringify(r))
  })
  t("sprint goal and the epic in flight", () => {
    ok(sprintGoal("x (Sprint 1, 8–21 November 2026: close our first school) y") === "Sprint 1, 8–21 November 2026: close our first school", "goal")
    ok(epicInFlight("| E8: Hogwarts Pilot | 2 | 5 | P0 | In Progress |") === "E8: Hogwarts Pilot (P0, in progress)", "epic")
  })
  const text = compile()
  const n = text.trimEnd().split("\n").length
  t(`the brief is ${MAX_LINES} lines or fewer (${n})`, () => ok(n <= MAX_LINES, `${n} lines`))
  t("it carries the Drive, the North Star, the sprint, the pilot and the price", () => {
    for (const h of ["## The Drive", "## North Star", "## Sprint", "## Pilot", "## Price", "## Why this film"]) ok(text.includes(h), h)
    ok(/Al-Ibda is client #1/.test(text), "pilot")
    ok(/24 SAR per student per year/.test(text) && /6\.4 USD/.test(text), "price")
    ok(/close our first school/.test(text), "sprint goal")
  })
  t("compile with empty sources still answers, never throws", () => ok(compile({ claude: "", star: "", ns: {}, epics: "", sprint: "", markets: {} }).includes("## The Drive"), "empty"))
  t("deterministic: the same sources give the same text", () => ok(compile() === compile(), "differs"))
  console.log(`company-brief: ${pass} passed, ${fails.length} failed`)
  return fails.length === 0
}

function main() {
  const a = process.argv.slice(2)
  if (a.includes("--test")) process.exit(runTests() ? 0 : 1)
  const text = compile()
  if (a.includes("--stdout")) return void process.stdout.write(text)
  if (a.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
    if (cur !== text) {
      console.error("company-brief: departments/_shared/company.md is out of date — run node .claude/scripts/company-brief.mjs")
      process.exit(1)
    }
    return void console.log("company-brief: up to date")
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, text)
  console.log(`company-brief: wrote ${path.relative(ROOT, OUT)} (${text.trimEnd().split("\n").length} lines)`)
}
if (process.argv[1] && path.resolve(process.argv[1]) === SELF) main()

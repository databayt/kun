// Shared helpers for `kun compile` — read the kun source, parse it, write native config safely.
//
// Model: an adapter's plan(ctx) is a PURE function of (kun source, what is on disk now) that returns a
// Plan — a list of ops (file / link / run). The runner (apply) compares each op with disk:
//   --check    report drift, write nothing          --dry-run   print what would be written
//   (default)  write what differs, back up a hand-made file before the first overwrite
// Merging (TOML / JSON / marker blocks) happens inside plan(), against the file as it is now, so a key kun
// does not own — a token, auth, a channel, a personal setting — is carried over untouched.
import {
  copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync,
  realpathSync, renameSync, rmSync, rmdirSync, statSync, symlinkSync, unlinkSync, writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, relative, resolve } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

export const HERE = dirname(fileURLToPath(import.meta.url));
export const KUN_ROOT = resolve(HERE, "../../..");
export const GEN = "generated by kun compile — edit kun, not this file";
export const MEMORY_POINTER =
  "Org memory: ~/kun/.claude/memory (read MEMORY.md / the index first; write new org facts as one-fact files under facts/; private files are decrypted to ~/.kun/memory-private/)";
const SKIP = new Set(["node_modules", ".DS_Store", ".git", "__pycache__"]);

// ── context ─────────────────────────────────────────────────────────────────────────────────
export function makeCtx({ kun = KUN_ROOT, home = process.env.KUN_COMPILE_HOME || homedir(), check = false, dryRun = false, quiet = false, write = false } = {}) {
  const targets = JSON.parse(readFileSync(join(kun, ".claude/targets.json"), "utf8"));
  return { kun, home, check, dryRun, quiet, write, targets, state: join(home, ".kun"), stamp: new Date().toISOString().replace(/[-:]/g, "").replace(/\..*/, "").replace("T", "-") };
}
export const expand = (ctx, p) => (p.startsWith("~/") ? join(ctx.home, p.slice(2)) : p === "~" ? ctx.home : p);
/** Resolved target path for (agent, kind), plus its transform name. */
export function target(ctx, agent, kind) {
  const a = ctx.targets.agents[agent];
  const t = a?.targets?.[kind];
  if (!t) throw new Error(`targets.json: no ${agent}.${kind}`);
  return { path: expand(ctx, t.path), transform: t.transform };
}
export const agentHome = (ctx, agent) => expand(ctx, ctx.targets.agents[agent].home);

// ── reading the kun source ─────────────────────────────────────────────────────────────────
export const read = (p) => (existsSync(p) ? readFileSync(p, "utf8") : null);

/** Minimal frontmatter parser: `key: value`, quoted strings, inline lists. Nested YAML is ignored. */
export function parseFrontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) return { data: {}, body: text };
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z0-9_$-]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith("[") && v.endsWith("]")) v = v.slice(1, -1).split(",").map((s) => unq(s.trim())).filter(Boolean);
    else v = unq(v);
    data[kv[1]] = v;
  }
  return { data, body: m[2] };
}
function unq(s) {
  if ((s.startsWith('"') && s.endsWith('"') && s.length > 1) || (s.startsWith("'") && s.endsWith("'") && s.length > 1)) {
    const inner = s.slice(1, -1);
    return s[0] === '"' ? inner.replace(/\\"/g, '"').replace(/\\\\/g, "\\") : inner;
  }
  return s;
}

export function loadAgents(ctx) {
  const dir = join(ctx.kun, ".claude/agents");
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith(".md") && !f.startsWith("_")).sort().map((f) => {
    const { data, body } = parseFrontmatter(readFileSync(join(dir, f), "utf8"));
    return { id: f.slice(0, -3), name: data.name || f.slice(0, -3), description: data.description || "", model: data.model, effort: data.effort, body: body.trim(), data };
  });
}
export function loadSkills(ctx) {
  const dir = join(ctx.kun, ".claude/skills");
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((n) => !SKIP.has(n) && existsSync(join(dir, n, "SKILL.md"))).sort().map((n) => {
    const { data } = parseFrontmatter(readFileSync(join(dir, n, "SKILL.md"), "utf8"));
    return { id: n, dir: join(dir, n), description: data.description || data.when_to_use || "", data };
  });
}
/** Files (relative paths) under dir, sorted, skipping junk. */
export function walk(dir) {
  const out = [];
  const go = (d) => { for (const n of readdirSync(d)) { if (SKIP.has(n) || n.endsWith(".pyc")) continue; const p = join(d, n); statSync(p).isDirectory() ? go(p) : out.push(relative(dir, p)); } };
  if (existsSync(dir)) go(dir);
  return out.sort();
}
/** MCP catalog → [{name, kind:'stdio'|'remote', command,args,env,url,skip}] with setup.sh's home substitution. */
export function loadMcp(ctx, { includeSkipped = false } = {}) {
  const raw = read(join(ctx.kun, ".claude/mcp.json"));
  if (!raw) return [];
  const data = JSON.parse(raw.split("/Users/abdout").join(ctx.home));
  const out = [];
  for (const [name, s] of Object.entries(data.mcpServers || {})) {
    if (!s || typeof s !== "object") continue;
    const skip = s.$skipRegistration === true;
    if (skip && !includeSkipped) continue;
    const remote = s.type === "http" || s.type === "sse" || s.url || s.serverUrl;
    if (remote) { const url = s.serverUrl || s.url; if (url) out.push({ name, kind: "remote", url, env: s.env, headers: s.headers, skip }); }
    else if (s.command) out.push({ name, kind: "stdio", command: s.command, args: s.args || [], env: s.env, skip });
  }
  return out;
}
/** "${VAR}" → "VAR", else null. */
export const envRef = (v) => { const m = /^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$/.exec(String(v)); return m ? m[1] : null; };

/** The shared instruction text: user CLAUDE.md template + every rules-global rule, as plain Markdown. */
export function compileInstructions(ctx, { title = "Kun — instructions" } = {}) {
  const parts = [];
  const tpl = read(join(ctx.kun, ".claude/templates/user-CLAUDE.md")) ?? read(join(ctx.kun, ".claude/CLAUDE.md")) ?? "";
  parts.push(tpl.trim());
  const rdir = join(ctx.kun, ".claude/rules-global");
  if (existsSync(rdir)) for (const f of readdirSync(rdir).filter((f) => f.endsWith(".md")).sort()) parts.push(`<!-- rule: ${f} -->\n${readFileSync(join(rdir, f), "utf8").trim()}`);
  parts.push(MEMORY_POINTER);
  return `<!-- ${GEN} -->\n<!-- ${title} -->\n\n${parts.join("\n\n---\n\n")}\n`;
}

// ── marker blocks (merge into a file we only partly own) ─────────────────────────────────────
export function blockMarkers(kind, comment = "#") {
  const [o, c] = comment === "<!--" ? ["<!--", "-->"] : [comment, ""];
  return { begin: `${o} >>> kun compile: ${kind} >>> ${GEN} ${c}`.trimEnd(), end: `${o} <<< kun compile: ${kind} <<< ${c}`.trimEnd() };
}
export function stripBlock(text, m) {
  const b = text.indexOf(m.begin);
  if (b < 0) return text;
  const e = text.indexOf(m.end, b);
  if (e < 0) return text;
  return (text.slice(0, b) + text.slice(e + m.end.length)).replace(/\n{3,}/g, "\n\n");
}
export function withBlock(text, m, body) {
  const base = stripBlock(text ?? "", m).replace(/\s+$/, "");
  return `${base}${base ? "\n\n" : ""}${m.begin}\n${body.replace(/\s+$/, "")}\n${m.end}\n`;
}

// ── plan + ops ─────────────────────────────────────────────────────────────────────────────
export class Plan {
  constructor(agent) { this.agent = agent; this.ops = []; this.notices = []; this.meta = {}; this.skipPrune = false; }
  file(path, content, { mode } = {}) { this.ops.push({ kind: "file", path, content: Buffer.isBuffer(content) ? content : Buffer.from(content), mode }); return this; }
  link(path, to) { this.ops.push({ kind: "link", path, to }); return this; }
  /** drift() → string|null (reason) ; fix is run only when drift is non-null and we are writing. */
  run(label, drift, cmd, args = [], opts = {}) { this.ops.push({ kind: "run", label, drift, cmd, args, opts }); return this; }
  notice(msg) { this.notices.push(msg); return this; }
}

const manifestPath = (ctx, agent) => join(ctx.state, "compile", `${agent}.json`);
export function readManifest(ctx, agent) {
  try { return JSON.parse(readFileSync(manifestPath(ctx, agent), "utf8")); } catch { return { files: [], meta: {} }; }
}
const same = (a, b) => a.length === b.length && a.equals(b);
const lex = (p) => { try { return lstatSync(p); } catch { return null; } };

function evalOp(ctx, op) {
  if (op.kind === "file") {
    const st = lex(op.path);
    if (!st) return "new";
    if (st.isSymbolicLink() || !st.isFile()) return "drift";
    return same(readFileSync(op.path), op.content) ? "ok" : "drift";
  }
  if (op.kind === "link") {
    const st = lex(op.path);
    if (!st) return "new";
    if (!st.isSymbolicLink()) return "drift";
    try { return realpathSync(op.path) === realpathSync(op.to) ? "ok" : "drift"; } catch { return readlinkSync(op.path) === op.to ? "ok" : "drift"; }
  }
  if (op.kind === "run") { const r = op.drift(); return r ? "drift" : "ok"; }
  return "ok";
}

function backup(ctx, agent, path) {
  const rel = path.startsWith(ctx.home) ? relative(ctx.home, path) : path.replace(/^\/+/, "_abs_/");
  const dest = join(ctx.state, "backup", agent, ctx.stamp, rel);
  mkdirSync(dirname(dest), { recursive: true });
  const st = lex(path);
  if (st.isSymbolicLink()) writeFileSync(dest + ".symlink", readlinkSync(path) + "\n");
  else if (st.isDirectory()) throw new Error(`refusing to replace directory ${path}`);
  else copyFileSync(path, dest);
  return dest;
}

/** Evaluate (and unless check/dry-run, apply) a plan. Returns {agent, results:[{op,path,status}], drift, notices}. */
export function apply(ctx, plan) {
  const agent = plan.agent;
  const old = readManifest(ctx, agent);
  const owned = new Set(old.files || []);
  const results = [];
  const now = new Set();
  for (const op of plan.ops) {
    if (op.path) now.add(op.path);
    const status = evalOp(ctx, op);
    results.push({ kind: op.kind, path: op.path || op.label, status, why: op.kind === "run" && status === "drift" ? op.drift() : undefined });
    if (status === "ok" || ctx.check || ctx.dryRun) continue;
    if (op.kind === "run") {
      const r = spawnSync(op.cmd, op.args, { stdio: ctx.quiet ? "ignore" : "inherit", ...op.opts });
      results.at(-1).ran = r.status === 0 ? "ok" : `exit ${r.status}`;
      continue;
    }
    mkdirSync(dirname(op.path), { recursive: true });
    if (lex(op.path) && !owned.has(op.path)) results.at(-1).backup = backup(ctx, agent, op.path);
    if (op.kind === "link") { rmSync(op.path, { force: true }); symlinkSync(op.to, op.path); }
    else {
      const tmp = `${op.path}.kun-tmp.${process.pid}`;
      writeFileSync(tmp, op.content, op.mode ? { mode: op.mode } : undefined);
      renameSync(tmp, op.path);
    }
  }
  // prune: files this adapter generated before that the source no longer produces
  if (!plan.skipPrune) for (const p of owned) {
    if (now.has(p) || !lex(p)) continue;
    results.push({ kind: "stale", path: p, status: "stale" });
    if (!ctx.check && !ctx.dryRun) { try { unlinkSync(p); for (let d = dirname(p); d.startsWith(ctx.home) && d !== ctx.home; d = dirname(d)) { try { rmdirSync(d); } catch { break; } } } catch { /* gone */ } }
  }
  if (!ctx.check && !ctx.dryRun) {
    const files = [...now].filter((p) => plan.ops.some((o) => o.path === p && o.kind !== "run"));
    mkdirSync(dirname(manifestPath(ctx, agent)), { recursive: true });
    writeFileSync(manifestPath(ctx, agent), JSON.stringify({ at: new Date().toISOString(), files: files.sort(), meta: plan.meta }, null, 2) + "\n");
  }
  const drift = results.filter((r) => r.status !== "ok");
  return { agent, results, drift, notices: plan.notices };
}

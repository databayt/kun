// opencode (~/.config/opencode). Writes into opencode.json: `mcp`, `agent`, `command`, `instructions` — and
// the files they point at (kun/AGENTS.md, kun/agents/*.md) plus skills/<name> symlinks.
// Preserved: "permission": "allow", model, small_model, provider (omniroute) and every key/entry kun does not own.
import { join } from "node:path";
import { Plan, compileInstructions, envRef, loadAgents, loadMcp, loadSkills, read, readManifest, target, agentHome } from "./lib.mjs";

export const transforms = { "instructions-md": 1, "agent-json": 1, "skill-link": 1, "skill-command": 1, "mcp-json": 1 };
const RESERVED_AGENTS = new Set(["build", "plan", "general", "explore"]);
const RESERVED_CMDS = new Set(["init", "undo", "redo", "share", "unshare", "help", "models", "themes", "sessions", "compact", "details", "export", "editor", "exit", "new", "connect", "thinking"]);

export function mcpEntry(s) {
  if (s.kind === "remote") return { type: "remote", url: s.url, enabled: true };
  const e = { type: "local", command: [s.command, ...s.args], enabled: true };
  const env = {};
  for (const [k, v] of Object.entries(s.env || {})) env[k] = envRef(v) ? `{env:${envRef(v)}}` : v;
  if (Object.keys(env).length) e.environment = env;
  return e;
}
export const agentKey = (id) => (RESERVED_AGENTS.has(id.toLowerCase()) ? `kun-${id.toLowerCase()}` : id);
export const cmdKey = (id) => (RESERVED_CMDS.has(id) ? `kun-${id}` : id);
const clip = (s, n = 200) => { const t = s.replace(/\s+/g, " ").trim(); return t.length > n ? t.slice(0, n - 1) + "…" : t; };

/** Merge kun's entries into an opencode.json object. Pure; `prev` = names kun generated last time. */
export function mergeOpencode(cfg, { mcp, agents, commands, instruction }, prev = {}) {
  const out = { ...cfg };
  const sect = (key, entries, old) => {
    const m = { ...(out[key] || {}) };
    for (const n of old || []) if (!(n in entries)) delete m[n];
    Object.assign(m, entries);
    if (Object.keys(m).length) out[key] = m; else delete out[key];
  };
  if (!out.$schema) out.$schema = "https://opencode.ai/config.json";
  sect("mcp", mcp, prev.mcp); sect("agent", agents, prev.agent); sect("command", commands, prev.command);
  const ins = Array.isArray(out.instructions) ? out.instructions.filter((i) => i !== instruction) : [];
  out.instructions = [...ins, instruction];
  return out;
}

export function plan(ctx) {
  const p = new Plan("opencode");
  const home = agentHome(ctx, "opencode");
  const insPath = target(ctx, "opencode", "instructions").path;
  p.file(insPath, compileInstructions(ctx, { title: "opencode — kun instructions" }));
  const agDir = target(ctx, "opencode", "agents").path;
  const agents = {};
  for (const a of loadAgents(ctx)) {
    const key = agentKey(a.id);
    p.file(join(agDir, `${key}.md`), `<!-- generated by kun compile — edit kun, not this file -->\n${a.body}\n`);
    agents[key] = { description: clip(a.description), mode: "subagent", prompt: `{file:${join(agDir, `${key}.md`)}}` };
  }
  const skillsDir = target(ctx, "opencode", "skills").path;
  const commands = {};
  const claudeSkills = join(agentHome(ctx, "claude"), "skills");
  for (const s of loadSkills(ctx)) {
    p.link(join(skillsDir, s.id), join(claudeSkills, s.id));
    commands[cmdKey(s.id)] = { description: clip(s.description, 160), template: `Use the ${s.id} skill: $ARGUMENTS` };
  }
  const mcp = {};
  for (const s of loadMcp(ctx)) mcp[s.name] = mcpEntry(s);
  const cfgPath = target(ctx, "opencode", "config").path;
  let cfg = {};
  const raw = read(cfgPath);
  if (raw) { try { cfg = JSON.parse(raw); } catch { p.notice(`${cfgPath} is not strict JSON — left unchanged`); return p; } }
  const prev = readManifest(ctx, "opencode").meta || {};
  const merged = mergeOpencode(cfg, { mcp, agents, commands, instruction: insPath }, prev);
  p.file(cfgPath, JSON.stringify(merged, null, 2) + "\n");
  p.meta = { mcp: Object.keys(mcp), agent: Object.keys(agents), command: Object.keys(commands) };
  void home;
  return p;
}

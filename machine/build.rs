//! Wires every feature into the shell, the way codebase generates `__registry__`.
//!
//! A feature is `src/components/machine/<feature>/rust.rs`. Each one becomes a module
//! (`crate::<feature>`) and, if it declares `#[tauri::command]`s, an inlined Tauri plugin
//! named after the folder, with `allow-<cmd>` permissions and a default that allows them all.
//! The optional sibling `capability.json` may list extra permissions the feature needs
//! (e.g. `dialog:allow-ask`). Everything feature-specific stays in the feature folder.

use std::{env, fmt::Write as _, fs, path::Path};

fn main() {
    let features_dir = Path::new("../src/components/machine")
        .canonicalize()
        .expect("src/components/machine must exist");
    println!("cargo:rerun-if-changed={}", features_dir.display());
    // MACHINE_ONLY=driver,chat limits the build to those features, so a builder working on
    // one feature is never blocked by another feature that is half-written.
    println!("cargo:rerun-if-env-changed=MACHINE_ONLY");
    let only: Option<Vec<String>> = env::var("MACHINE_ONLY").ok().map(|v| {
        v.split(',')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect()
    });

    let mut features: Vec<(String, Vec<String>, Vec<String>)> = Vec::new();
    let mut entries: Vec<_> = fs::read_dir(&features_dir)
        .expect("read features dir")
        .filter_map(Result::ok)
        .filter(|e| e.path().join("rust.rs").is_file())
        .filter(|e| {
            only.as_ref()
                .is_none_or(|o| o.iter().any(|n| *n == e.file_name().to_string_lossy()))
        })
        .collect();
    entries.sort_by_key(fs::DirEntry::file_name);

    for entry in entries {
        let name = entry.file_name().to_string_lossy().to_string();
        assert!(
            name.chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "feature folder `{name}` must be a lowercase Rust identifier"
        );
        let dir = entry.path();
        // Watch the whole feature folder: rust.rs plus any split siblings and capability.json.
        println!("cargo:rerun-if-changed={}", dir.display());
        let commands = commands_in(&dir);
        let extra = extra_permissions(&dir.join("capability.json"));
        features.push((name, commands, extra));
    }

    // 1. features.rs — module lines + plugin registration, included by lib.rs.
    let mut out = String::from("// @generated by machine/build.rs — do not edit.\n");
    for (name, _, _) in &features {
        let path = features_dir.join(name).join("rust.rs");
        writeln!(
            out,
            "#[path = {:?}]\npub mod {name};",
            path.display().to_string()
        )
        .ok();
    }
    out.push_str("\n/// Registers every feature that exposes commands as an inlined plugin.\n");
    out.push_str("pub(crate) fn register<R: tauri::Runtime>(builder: tauri::Builder<R>) -> tauri::Builder<R> {\n    builder");
    for (name, commands, _) in &features {
        if !commands.is_empty() {
            write!(out, "\n        .plugin({name}::plugin())").ok();
        }
    }
    out.push_str("\n}\n");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR");
    fs::write(Path::new(&out_dir).join("features.rs"), out).expect("write features.rs");

    // 2. capabilities/features.json — one capability for the main window, scoped to the
    //    /<lang>/machine routes of kun (prod) and localhost:3000 (dev).
    let mut permissions: Vec<String> = vec!["core:default".into()];
    for (name, commands, extra) in &features {
        if !commands.is_empty() {
            permissions.push(format!("{name}:default"));
        }
        permissions.extend(extra.iter().cloned());
    }
    permissions.dedup();
    let capability = serde_json_like(&permissions);
    fs::create_dir_all("capabilities").ok();
    let existing = fs::read_to_string("capabilities/features.json").unwrap_or_default();
    if existing != capability {
        fs::write("capabilities/features.json", capability).expect("write capability");
    }

    // 3. Inlined plugins — permissions generated from the command names.
    let mut attrs = tauri_build::Attributes::new();
    for (name, commands, _) in features {
        if commands.is_empty() {
            continue;
        }
        let name: &'static str = Box::leak(name.into_boxed_str());
        let commands: &'static [&'static str] = Box::leak(
            commands
                .into_iter()
                .map(|c| &*Box::leak(c.into_boxed_str()))
                .collect::<Vec<&'static str>>()
                .into_boxed_slice(),
        );
        attrs = attrs.plugin(
            name,
            tauri_build::InlinedPlugin::new()
                .commands(commands)
                .default_permission(tauri_build::DefaultPermissionRule::AllowAllCommands),
        );
    }
    tauri_build::try_build(attrs).expect("tauri build");
}

/// Names of `#[tauri::command]` functions in rust.rs and its split siblings.
fn commands_in(dir: &Path) -> Vec<String> {
    let mut names = Vec::new();
    let mut files: Vec<_> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| {
            p.extension().is_some_and(|x| x == "rs") && !p.to_string_lossy().ends_with("_test.rs")
        })
        .collect();
    files.sort();
    for file in files {
        let src = fs::read_to_string(&file).unwrap_or_default();
        let mut armed = false;
        for line in src.lines() {
            let t = line.trim();
            if t.starts_with("#[tauri::command") {
                armed = true;
            } else if armed
                && (t.starts_with("pub") || t.starts_with("async fn") || t.starts_with("fn"))
            {
                if let Some(rest) = t.split("fn ").nth(1) {
                    let name: String = rest
                        .chars()
                        .take_while(|c| c.is_alphanumeric() || *c == '_')
                        .collect();
                    names.push(name);
                }
                armed = false;
            }
        }
    }
    names
}

/// Extra permission identifiers from a feature's optional capability.json (`{"permissions": [...]}`).
fn extra_permissions(path: &Path) -> Vec<String> {
    let Ok(src) = fs::read_to_string(path) else {
        return Vec::new();
    };
    let Some(start) = src.find('[') else {
        return Vec::new();
    };
    let Some(end) = src[start..].find(']') else {
        return Vec::new();
    };
    src[start + 1..start + end]
        .split(',')
        .map(|s| s.trim().trim_matches('"').to_string())
        .filter(|s| !s.is_empty())
        .collect()
}

fn serde_json_like(permissions: &[String]) -> String {
    let perms = permissions
        .iter()
        .map(|p| format!("    {p:?}"))
        .collect::<Vec<_>>()
        .join(",\n");
    format!(
        r#"{{
  "$schema": "../gen/schemas/remote-schema.json",
  "identifier": "features",
  "description": "@generated by build.rs: every machine feature, for the main window, on the /<lang>/machine routes only.",
  "windows": ["main"],
  "local": true,
  "remote": {{
    "urls": [
      "https://kun.databayt.org/*/machine",
      "https://kun.databayt.org/*/machine/*",
      "http://localhost:3000/*/machine",
      "http://localhost:3000/*/machine/*"
    ]
  }},
  "permissions": [
{perms}
  ]
}}
"#
    )
}

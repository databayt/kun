//! Workspace: the folder a profile's runs live in, `~/Kun/<login>/`.
//!
//! ```text
//! ~/Kun/<login>/            CLAUDE.md AGENTS.md KNOWLEDGE.md .claude-settings.json .claude/skills/…
//!      <login>/work/        the only place a read-only profile may write
//! ~/Kun/repos/<name>/       the profile's public repos (the repos feature), read-only for the run
//! ```
//!
//! Everything but `work/` is regenerated on every call, so it is idempotent and never drifts.

use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use serde_json::json;

use super::{PackError, io_err, link, meta_in, valid_name, write_if_changed};
use crate::profile::{Access, CodeAccess, MachineProfile, WorkspaceAccess};

/// The paths a run needs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Workspace {
    pub dir: PathBuf,
    pub repos: PathBuf,
    pub work: PathBuf,
    pub settings_file: PathBuf,
}

/// A path as Claude Code's permission rules spell it: `//` + absolute POSIX path; on Windows
/// `C:\Users\x` becomes `//c/Users/x`.
#[must_use]
pub(super) fn rule_path(path: &Path) -> String {
    let raw = path.display().to_string().replace('\\', "/");
    let bytes = raw.as_bytes();
    let posix = if bytes.len() >= 2 && bytes[1] == b':' && bytes[0].is_ascii_alphabetic() {
        format!("/{}{}", raw[..1].to_ascii_lowercase(), &raw[2..])
    } else {
        raw
    };
    format!("/{}", posix.trim_end_matches('/'))
}

/// The `--settings` file: read-only code is a deny list, the workspace's `work/` an allow.
#[must_use]
pub fn settings_json(repos: &Path, work: &Path, access: &Access) -> String {
    let repos_rule = rule_path(repos);
    let work_rule = rule_path(work);
    let mut deny: Vec<String> = Vec::new();
    let mut allow: Vec<String> = Vec::new();
    if access.code == CodeAccess::Read {
        deny.extend([
            format!("Edit({repos_rule}/**)"),
            format!("Write({repos_rule}/**)"),
            "Bash(git push*)".into(),
            "Bash(git commit*)".into(),
            "Bash(rm *)".into(),
        ]);
    }
    if access.workspace == WorkspaceAccess::Write {
        allow.extend([
            format!("Edit({work_rule}/**)"),
            format!("Write({work_rule}/**)"),
        ]);
    } else {
        deny.extend([
            format!("Edit({work_rule}/**)"),
            format!("Write({work_rule}/**)"),
        ]);
    }
    let value = json!({ "permissions": { "allow": allow, "deny": deny } });
    let mut out = serde_json::to_string_pretty(&value).unwrap_or_default();
    out.push('\n');
    out
}

fn first_lines(text: &str, count: usize, width: usize) -> String {
    text.lines()
        .map(str::trim)
        .filter(|l| {
            !l.is_empty() && !l.starts_with('#') && !l.starts_with("---") && !l.starts_with("<!--")
        })
        .take(count)
        .collect::<Vec<_>>()
        .join(" ")
        .chars()
        .take(width)
        .collect()
}

fn frontmatter(text: &str, key: &str) -> Option<String> {
    let body = text.strip_prefix("---")?;
    let block = &body[..body.find("\n---")?];
    block.lines().find_map(|l| {
        let (k, v) = l.split_once(':')?;
        (k.trim() == key).then(|| v.trim().trim_matches(['"', '\'']).to_owned())
    })
}

fn heading(text: &str) -> Option<String> {
    text.lines()
        .find_map(|l| l.strip_prefix("# ").map(|h| h.trim().to_owned()))
}

/// A repo's folder: the clone under `repos/`, or kun's own checkout for `kun`.
fn repo_dir(kun: &Path, repos: &Path, name: &str) -> Option<PathBuf> {
    let clone = repos.join(name);
    if clone.is_dir() {
        Some(clone)
    } else if name == "kun" && kun.is_dir() {
        Some(kun.to_path_buf())
    } else {
        None
    }
}

/// The generated knowledge map: where each feature is explained, and how to explain one.
#[must_use]
// One linear document template, section after section; splitting it would only scatter the text.
#[allow(clippy::too_many_lines)]
pub(super) fn knowledge_md(kun: &Path, repos: &Path, profile: &MachineProfile) -> String {
    let mut out = String::from(
        "# KNOWLEDGE — خريطة المعرفة\n\n\
         Generated by machine on every run. Read the file a line points to before you answer, and cite it.\n\
         اقرأ الملف الذي يشير إليه السطر قبل أن تجيب، واذكره في إجابتك.\n\n",
    );

    out.push_str("## kun — org, products, team, pricing (content/docs)\n\n");
    let kun_root = repo_dir(kun, repos, "kun").unwrap_or_else(|| kun.to_path_buf());
    let mut docs: Vec<PathBuf> = walkdir::WalkDir::new(kun_root.join("content/docs"))
        .max_depth(2)
        .into_iter()
        .flatten()
        .filter(|e| {
            e.file_type().is_file()
                && e.path()
                    .extension()
                    .is_some_and(|x| x == "mdx" || x == "md")
        })
        .map(walkdir::DirEntry::into_path)
        .collect();
    docs.sort();
    for path in docs.iter().take(300) {
        let text = fs::read_to_string(path).unwrap_or_default();
        let title = frontmatter(&text, "title")
            .or_else(|| heading(&text))
            .unwrap_or_else(|| {
                path.file_stem()
                    .map(|s| s.to_string_lossy().into_owned())
                    .unwrap_or_default()
            });
        let desc = frontmatter(&text, "description").unwrap_or_default();
        let _ = writeln!(
            out,
            "- **{title}** — `{}`{}",
            path.display(),
            if desc.is_empty() {
                String::new()
            } else {
                format!(" — {desc}")
            }
        );
    }
    if docs.is_empty() {
        out.push_str("_No content/docs found in this checkout._\n");
    }

    if let Some(hogwarts) = profile
        .repos
        .iter()
        .any(|r| r == "hogwarts")
        .then(|| repo_dir(kun, repos, "hogwarts"))
        .flatten()
    {
        out.push_str("\n## hogwarts — the blocks (src/components/**/README.md)\n\n");
        let mut readmes: Vec<PathBuf> = walkdir::WalkDir::new(hogwarts.join("src/components"))
            .max_depth(3)
            .into_iter()
            .flatten()
            .filter(|e| e.file_type().is_file() && e.file_name() == "README.md")
            .map(walkdir::DirEntry::into_path)
            .collect();
        readmes.sort();
        for path in readmes.iter().take(200) {
            let text = fs::read_to_string(path).unwrap_or_default();
            let block = path
                .parent()
                .and_then(|p| p.strip_prefix(hogwarts.join("src/components")).ok())
                .map(|p| p.display().to_string())
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "- **{block}** — `{}` — {}",
                path.display(),
                first_lines(&text, 3, 240)
            );
        }
        if readmes.is_empty() {
            out.push_str(
                "_No block READMEs found; read the folders under src/components directly._\n",
            );
        }
    }

    if let Some(mkan) = profile
        .repos
        .iter()
        .any(|r| r == "mkan")
        .then(|| repo_dir(kun, repos, "mkan"))
        .flatten()
    {
        out.push_str("\n## mkan — rentals marketplace\n\n");
        let readme = mkan.join("README.md");
        let text = fs::read_to_string(&readme).unwrap_or_default();
        let _ = writeln!(
            out,
            "`{}`\n\n{}",
            readme.display(),
            text.lines().take(40).collect::<Vec<_>>().join("\n")
        );
    }

    out.push_str(
        "\n## Explain a feature — اشرح ميزة\n\n\
         1. **What** — ما هي؟ One sentence, from the README and the code, not from memory.\n\
         2. **Who** — من يستخدمها؟ The role (teacher, parent, admin, student) and the screen they see.\n\
         3. **30-second pitch** — عرض ٣٠ ثانية: the problem, the feature, the result.\n\
         4. **Demo path** — مسار العرض: route by route, the clicks in order, with the demo data to use.\n\
         5. **Video shot list** — قائمة اللقطات: one line per shot (screen, action, caption).\n\n\
         Cite every file you read. If the code does not show it, say so; never invent a feature.\n",
    );
    out
}

fn claude_md(kun: &Path, repos: &Path, work: &Path, profile: &MachineProfile) -> String {
    let mut out = format!(
        "# {} — Kun workspace\n\n",
        if profile.name.is_empty() {
            &profile.login
        } else {
            &profile.name
        }
    );
    out.push_str(
        "## Knowledge rules — قواعد المعرفة\n\
         - Answer from `KNOWLEDGE.md` and the code it points to. Read the file first; cite its path.\n\
         - Arabic first (RTL), English mirrored.\n\
         - Say \"I did not find it\" instead of guessing. Never invent a feature, a price or a number.\n\
         - اجعل الجواب بالعربية أولاً، واذكر الملف الذي قرأته.\n\n",
    );
    out.push_str("## Folders\n");
    let _ = writeln!(out, "- Repos (read-only): `{}`", repos.display());
    for r in &profile.repos {
        let _ = writeln!(out, "  - `{}`", repos.join(r).display());
    }
    let _ = writeln!(out, "- Write here only: `{}`\n", work.display());
    for dept in profile
        .departments
        .iter()
        .map(|d| d.name.as_str())
        .filter(|d| valid_name(d))
    {
        let prompt = fs::read_to_string(kun.join("departments").join(dept).join("prompt.md"))
            .unwrap_or_default();
        if !prompt.trim().is_empty() {
            let _ = write!(out, "---\n\n{}\n\n", prompt.trim_end());
        }
    }
    out
}

/// Builds (or refreshes) the profile's workspace.
///
/// # Errors
/// On a login or department that is not a plain name, or a filesystem failure.
pub fn ensure_workspace_in(
    kun: &Path,
    root: &Path,
    profile: &MachineProfile,
) -> Result<Workspace, PackError> {
    if !valid_name(&profile.login) {
        return Err(PackError::BadName);
    }
    let dir = root.join(&profile.login);
    let repos = root.join("repos");
    let work = dir.join("work");
    let settings_file = dir.join(".claude-settings.json");
    fs::create_dir_all(&work).map_err(io_err(&work))?;
    fs::create_dir_all(&repos).map_err(io_err(&repos))?;

    let claude = claude_md(kun, &repos, &work, profile);
    write_if_changed(&dir.join("CLAUDE.md"), &claude)?;
    write_if_changed(&dir.join("AGENTS.md"), &claude)?;
    write_if_changed(
        &dir.join("KNOWLEDGE.md"),
        &knowledge_md(kun, &repos, profile),
    )?;
    write_if_changed(
        &settings_file,
        &settings_json(&repos, &work, &profile.access),
    )?;

    let mut wanted: Vec<String> = Vec::new();
    for dept in &profile.departments {
        for name in meta_in(kun, &dept.name)?.skills {
            if !wanted.contains(&name) && !profile.hidden.contains(&format!("skill:{name}")) {
                wanted.push(name);
            }
        }
    }
    link::link_skills(
        &kun.join(".claude/skills"),
        &dir.join(".claude/skills"),
        &wanted,
    )?;
    let agents = kun.join(".agents/skills");
    if agents.is_dir() {
        link::link_skills(&agents, &dir.join(".agents/skills"), &wanted)?;
    }
    Ok(Workspace {
        dir,
        repos,
        work,
        settings_file,
    })
}
